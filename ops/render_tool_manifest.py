def load_pin() -> dict[str, str]:
    with MANIFEST.open("rb") as fh:
        data = tomllib.load(fh)
    j = data["jankurai"]
    required = (
        "repo",
        "tag",
        "rev",
        "version",
        "semver",
        "source_tree",
        "source_archive_sha256",
        "cargo_lock_sha256",
        "binary_sha256",
        "rust_toolchain",
        "rustc_version",
        "cargo_version",
        "target_triple",
        "build_mode",
    )
    missing = [key for key in required if not j.get(key)]
    if missing:
        raise SystemExit(f"tool-manifest.toml [jankurai] missing: {', '.join(missing)}")
    pin = {key: str(j[key]) for key in required}
    if pin["repo"] != "http://127.0.0.1:8787/git/jeryu/jankurai.git":
        raise SystemExit("Jankurai release source must be the approved local Jeryu forge URL")
    for key in ("rev", "source_tree"):
        if not re.fullmatch(r"[0-9a-f]{40}", pin[key]):
            raise SystemExit(f"invalid {key}: expected 40 lowercase hexadecimal characters")
    for key in ("source_archive_sha256", "cargo_lock_sha256", "binary_sha256"):
        if not re.fullmatch(r"[0-9a-f]{64}", pin[key]):
            raise SystemExit(f"invalid {key}: expected SHA-256")
    return pin


def pin_env_text(pin: dict[str, str]) -> str:
    lines = [
        "# GENERATED by ops/render-tool-manifest.sh from tool-manifest.toml — DO NOT EDIT.",
        "# This binds source, build environment, and installed binary identity.",
    ]
    lines.extend(f'{env}="{pin[key]}"' for env, key in PIN_ENV_FIELDS)
    return "\n".join(lines) + "\n"


